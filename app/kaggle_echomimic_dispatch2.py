from __future__ import annotations
import json, os, shutil, subprocess, sys, time
from pathlib import Path

ROOT=Path(__file__).resolve().parents[1]
OUT=ROOT/'output'
KDIR=ROOT/'.kaggle_worker'
DDIR=ROOT/'.kaggle_dataset'
INPUT_DATASET='bhajanaabha/hindibhajans-echomimic-inputs'
KERNEL_PREFIX='bhajanaabha/hindibhajans-echomimic'

def run(cmd,env):
    print('RUN:',*cmd,flush=True)
    p=subprocess.run(cmd,cwd=ROOT,env=env,text=True,capture_output=True)
    if p.stdout:
        print(p.stdout,end='',flush=True)
    if p.stderr:
        print(p.stderr,end='',flush=True)
    return p

def wait_dataset(env,timeout=900):
    deadline=time.time()+timeout
    while time.time()<deadline:
        p=subprocess.run(['kaggle','datasets','status',INPUT_DATASET,'--format','json'],cwd=ROOT,env=env,capture_output=True,text=True)
        s=(p.stdout+p.stderr).strip(); print('DATASET_STATUS',s,flush=True)
        if p.returncode==0:
            low=s.lower()
            if any(x in low for x in ('complete','ready','success')): return
            if any(x in low for x in ('error','failed','cancelled','canceled')): raise RuntimeError('KAGGLE_DATASET_FAILED '+s)
        time.sleep(15)
    raise TimeoutError('KAGGLE_DATASET_TIMEOUT')

def publish_inputs(env,image,audio,seconds):
    shutil.rmtree(DDIR,ignore_errors=True); DDIR.mkdir(parents=True)
    shutil.copy2(image,DDIR/'singer.png'); shutil.copy2(audio,DDIR/'bhajan.mp3'); (DDIR/'duration.txt').write_text(str(seconds))
    (DDIR/'dataset-metadata.json').write_text(json.dumps({
        'title':'HindiBHajans EchoMimic Runtime Inputs','id':INPUT_DATASET,
        'subtitle':'Private per-run inputs shared with the video worker',
        'description':'Private runtime input package generated by GitHub Actions.',
        'licenses':[{'name':'other'}]},indent=2))
    st=subprocess.run(['kaggle','datasets','status',INPUT_DATASET,'--format','json'],cwd=ROOT,env=env,capture_output=True,text=True)
    if st.returncode==0:
        run(['kaggle','datasets','version','-p',str(DDIR),'-m',f'EchoMimic runtime inputs {seconds}s','-d'],env)
    else:
        run(['kaggle','datasets','create','-p',str(DDIR)],env)
    wait_dataset(env)

def wait_kernel(env,kernel):
    deadline=time.time()+115*60
    queued_since = None
    MAX_QUEUE_WAIT = 35 * 60
    while time.time()<deadline:
        p=subprocess.run(['kaggle','kernels','status',kernel],cwd=ROOT,env=env,capture_output=True,text=True)
        status=(p.stdout+p.stderr).strip(); print(status,flush=True); low=status.lower()
        if 'complete' in low and not any(x in low for x in ('incomplete','not complete')): return True,status
        if 'queued' in low:
            if queued_since is None:
                queued_since = time.time()
            elif time.time() - queued_since > MAX_QUEUE_WAIT:
                return False, 'KAGGLE_GPU_QUEUE_TIMEOUT: Kernel remained in QUEUED status for >15 minutes.'
        else:
            queued_since = None
        if any(x in low for x in ('error','failed','cancelled','canceled','cancel_acknowledged','cancel acknowledged')):
            log=subprocess.run(['kaggle','kernels','logs',kernel],cwd=ROOT,env=env,capture_output=True,text=True)
            log_text = log.stdout or log.stderr or ''
            err_details = [f'status={status}', log_text]
            err_dir = OUT/'kaggle_video_error_output'; shutil.rmtree(err_dir, ignore_errors=True); err_dir.mkdir(parents=True)
            op = subprocess.run(['kaggle','kernels','output',kernel,'-p',str(err_dir),'--force'],cwd=ROOT,env=env,capture_output=True,text=True)
            for f in sorted(err_dir.rglob('*')):
                if f.is_file() and f.stat().st_size < 2_000_000 and not f.name.endswith(('.mp4','.png','.jpg','.onnx','.pth','.bin')):
                    try:
                        err_details.append(f'=== {f.name} ===\n' + f.read_text(encoding='utf-8', errors='replace'))
                    except Exception: pass
            return False, 'KAGGLE_KERNEL_TERMINAL_FAILURE\n' + '\n'.join(err_details)
        time.sleep(30)
    return False,'KAGGLE_KERNEL_TIMEOUT'

def run_kernel(env,kernel):
    shutil.rmtree(KDIR,ignore_errors=True); KDIR.mkdir(parents=True)
    # Kaggle script kernels execute only the metadata code_file; extra .py files in the
    # push directory are not guaranteed to appear in /kaggle/working. Embed the QA
    # helper into the worker bootstrap so the worker is self-contained.
    import base64
    worker_src=(ROOT/'app'/'kaggle_echomimic_worker.py').read_text(encoding='utf-8')
    gate_src=(ROOT/'app'/'lipsync_quality_gate.py').read_bytes()
    gate_b64=base64.b64encode(gate_src).decode('ascii')
    bootstrap=("import base64\n"
               "from pathlib import Path\n"
               f"Path('/kaggle/working/lipsync_quality_gate.py').write_bytes(base64.b64decode({gate_b64!r}))\n")
    marker="from __future__ import annotations\n"
    if marker not in worker_src:
        raise RuntimeError('EchoMimic worker missing future-import marker')
    worker_src=worker_src.replace(marker,marker+bootstrap,1)
    (KDIR/'worker.py').write_text(worker_src,encoding='utf-8')
    (KDIR/'lipsync_quality_gate.py').write_bytes(gate_src)
    meta={'id':kernel,'title':kernel.rsplit('/',1)[-1],'code_file':'worker.py','language':'python','kernel_type':'script',
          'is_private':True,'enable_gpu':True,'enable_internet':True,'machine_shape':'NvidiaTeslaT4',
          'dataset_sources':[INPUT_DATASET],'competition_sources':[],'kernel_sources':[],'model_sources':[]}
    (KDIR/'kernel-metadata.json').write_text(json.dumps(meta,indent=2))
    run([sys.executable,'-m','py_compile',str(KDIR/'worker.py'),str(KDIR/'lipsync_quality_gate.py')],env)
    push=run(['kaggle','kernels','push','-p',str(KDIR),'--accelerator','NvidiaTeslaT4','--timeout',str(7200)],env)
    push_text=(push.stdout or '')+'\n'+(push.stderr or '')
    low=push_text.lower()
    if 'maximum weekly gpu quota' in low or ('gpu quota' in low and 'reached' in low):
        raise RuntimeError('KAGGLE_GPU_QUOTA_EXHAUSTED: Kaggle refused GPU allocation before the EchoMimic kernel was created. Do not retry; wait for quota reset.')
    if push.returncode != 0:
        raise RuntimeError(f'KAGGLE_KERNEL_PUSH_FAILED: {push_text.strip()}')
    return wait_kernel(env,kernel)

def main(seconds):
    token=os.getenv('KAGGLE_API_TOKEN') or os.getenv('KAGGLE_API_TOKEN3')
    if not token: raise RuntimeError('KAGGLE_API_TOKEN missing')
    from app.deity_catalog import get_daily_bhajan
    daily_entry = get_daily_bhajan()
    deity_scene = ROOT / 'assets' / 'deities' / daily_entry.get('scene_file', '')
    image = deity_scene if deity_scene.exists() else (ROOT / 'assets' / 'singer_image.png')
    audio = OUT / 'bhajan_source.mp3'
    if not image.exists() or not audio.exists(): raise RuntimeError('canonical inputs missing')
    if not 180<=seconds<=300 or seconds%15: raise RuntimeError(f'invalid duration {seconds}')
    print(f'ECHOMIMIC_INPUT_SCENE={image.name} DEITY={daily_entry["deity"]}', flush=True)
    env=dict(os.environ); env['KAGGLE_API_TOKEN']=token
    publish_inputs(env,image,audio,seconds)
    run_id=os.getenv('GITHUB_RUN_ID','manual')
    # Check if a completed kernel from an earlier attempt of this run already produced the master video
    check_kernels = [
        f'{KERNEL_PREFIX}-{run_id}-1'.lower(),
        f'{KERNEL_PREFIX}-{run_id}-2'.lower(),
    ]
    for prev_k in check_kernels:
        st = subprocess.run(['kaggle','kernels','status',prev_k], cwd=ROOT, env=env, capture_output=True, text=True)
        s_out = (st.stdout + st.stderr).lower()
        if st.returncode == 0 and 'complete' in s_out and not any(x in s_out for x in ('incomplete', 'not complete')):
            print(f'Checking output of completed kernel {prev_k}...', flush=True)
            dest = OUT/'kaggle_output'; shutil.rmtree(dest, ignore_errors=True); dest.mkdir(parents=True)
            run(['kaggle','kernels','output',prev_k,'-p',str(dest),'--force','--file-pattern',r'.*(master\.mp4|lipsync_qa\.json)$'], env)
            files = list(dest.rglob('master.mp4'))
            qa = list(dest.rglob('lipsync_qa.json'))
            if files and qa and files[0].stat().st_size > 500_000:
                shutil.copy2(files[0], OUT/'master.mp4')
                shutil.copy2(qa[0], OUT/'lipsync_qa.json')
                print(f'KAGGLE_ECHOMIMIC_REUSED_COMPLETED_KERNEL={prev_k}', flush=True)
                return
    print('Waiting 60s for Kaggle GPU worker slot to cleanly release from previous audio step...', flush=True)
    time.sleep(60)
    for attempt in (1, 2):
        kernel=f'{KERNEL_PREFIX}-{run_id}-{attempt}'.lower()
        print(f'ECHOMIMIC_KERNEL={kernel}',flush=True)
        ok,detail=run_kernel(env,kernel)
        if ok:
            dest=OUT/'kaggle_output'; shutil.rmtree(dest,ignore_errors=True); dest.mkdir(parents=True)
            run(['kaggle','kernels','output',kernel,'-p',str(dest),'--force','--file-pattern',r'.*(master\.mp4|lipsync_qa\.json)$'],env)
            files=list(dest.rglob('master.mp4'))
            qa=list(dest.rglob('lipsync_qa.json'))
            if not files: raise RuntimeError('KAGGLE_COMPLETED_BUT_MASTER_MP4_MISSING')
            if not qa: raise RuntimeError('KAGGLE_COMPLETED_BUT_LIPSYNC_QA_MISSING')
            shutil.copy2(files[0],OUT/'master.mp4')
            shutil.copy2(qa[0],OUT/'lipsync_qa.json')
            print('KAGGLE_ECHOMIMIC_MASTER_READY',flush=True)
            print('KAGGLE_LIPSYNC_QA_READY',flush=True)
            return
        print(detail,flush=True)
        # A worker ERROR containing a traceback is an application/dependency failure,
        # not a transient Kaggle kernel-state problem. Retrying would burn GPU quota
        # without changing the code. Only retry clean terminal kernel-state failures.
        detail_low=detail.lower()
        non_retryable=('traceback','importerror','modulenotfounderror','dependency_smoke_failed','lipsync_quality_gate_failed','syncnet_model_sha256_mismatch','out of memory','cuda out of memory')
        if any(x in detail_low for x in non_retryable):
            raise RuntimeError('KAGGLE_ECHOMIMIC_WORKER_NONRETRYABLE_FAILURE: '+detail)
        if attempt < 2:
            print(f'ECHOMIMIC_AUTO_RETRY={attempt} terminal Kaggle state; waiting 90s before fresh kernel slug',flush=True)
            time.sleep(90)
    raise RuntimeError('KAGGLE_ECHOMIMIC_KERNEL_FAILED_AFTER_RETRY')

if __name__=='__main__':
    import argparse
    ap=argparse.ArgumentParser(); ap.add_argument('--seconds',type=int,default=180)
    main(ap.parse_args().seconds)
